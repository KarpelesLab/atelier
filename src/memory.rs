    #[test]
    fn secrets_are_refused() {
        for secret in [
            "-----BEGIN OPENSSH PRIVATE KEY-----\nb3BlbnNzaC1rZXk\n",
            "-----BEGIN PRIVATE KEY-----",
            "the key is sk-proj-abcdefghijklmnopqrstuvwx",
            "ghp_abcdefghijklmnopqrstuvwxyz0123456789",
            "github_pat_11ABCDEFG0abcdefghijkl_mnopqrstuv",
            "aws AKIAIOSFODNN7EXAMPLE",
            "xoxb-123456789012-abcdefghij",
            "password=hunter2",
            "DB_PASSWORD = \"hunter2\"",
            "api_key: abcd1234",
            "Authorization: Bearer abcdefghijklmnopqrstuvwxyz",
        ] {
            assert!(secret_kind(secret).is_some(), "should refuse {secret:?}");
        }
        for fine in [
            "The API key lives in the DEPLOY_KEY environment variable.",
            "Ask before touching the password reset flow.",
            "Tokens are budgeted at 2000 per turn.",
            "Use the sk- prefix convention from the vendor docs.",
            "The task-runner is `just`; risk-averse about migrations.",
        ] {
            assert_eq!(secret_kind(fine), None, "should accept {fine:?}");
        }

        let (store, _, _) = store("secrets");
        let m = memory("db", Kind::Project, "connect with password=hunter2");
        let err = store.save(Scope::Project, &m).unwrap_err().to_string();
        assert!(err.contains("looks like it contains a secret"), "{err}");
        assert!(store.list().is_empty());
        // The description is checked too.
        let mut m = memory("db", Kind::Project, "fine");
        m.description = "token: abcd1234efgh".to_string();
        assert!(store.save(Scope::Project, &m).is_err());
    }

    #[cfg(unix)]
    #[test]
    fn symlinks_are_not_followed() {
        let (store, root, _) = store("symlink");
        let outside = root.parent().unwrap().join("outside.txt");
        std::fs::write(&outside, "private").unwrap();
        let dir = root.join(".atelier/memory");
        std::fs::create_dir_all(&dir).unwrap();
        std::os::unix::fs::symlink(&outside, dir.join("leak.md")).unwrap();

        assert!(store.list().is_empty());
        assert!(store.read("leak", None).is_err());
        assert!(
            store
                .save(Scope::Project, &memory("leak", Kind::Project, "b"))
                .is_err()
        );
        assert_eq!(std::fs::read_to_string(&outside).unwrap(), "private");

        // Nor a memory directory that itself points out of the project.
        std::fs::remove_dir_all(&dir).unwrap();
        let elsewhere = root.parent().unwrap().join("elsewhere");
        std::fs::create_dir_all(&elsewhere).unwrap();
        std::fs::write(elsewhere.join("note.md"), "private").unwrap();
        std::os::unix::fs::symlink(&elsewhere, &dir).unwrap();
        assert!(store.list().is_empty());
        let err = store
            .save(Scope::Project, &memory("x", Kind::Project, "b"))
            .unwrap_err()
            .to_string();
        assert!(err.contains("outside the project"), "{err}");
    }

